"""Consistent pseudonymizer: same input -> same pseudonym, every time.

Flow:

1. Run Presidio analysis on the input text.
2. Drop overlapping detections, keeping the widest span, so a replacement never
   lands on text an earlier replacement already rewrote.
3. For each entity, compute an HMAC-SHA256 of the original value with the
   server-side salt. The mapping store keys on the HMAC; the plaintext never
   leaves this function.
4. ``mapping_store.lookup_or_create`` returns a stable pseudonym, generated by a
   type-specific Faker generator the first time a given hash is seen.
5. Replace occurrences right to left so earlier offsets stay valid.

Reversibility lives in the mapping store: deleting a row by
``(entity_type, original_hash)`` invalidates all future lookups for that value
without touching the corpus.
"""

from __future__ import annotations

import hashlib
import hmac
from collections.abc import Callable
from dataclasses import dataclass

from faker import Faker
from presidio_analyzer import AnalyzerEngine

from app.ingestion.pii.mapping_store import MappingStore


@dataclass(frozen=True)
class AppliedMapping:
    """One entity that was replaced in the input text."""

    entity_type: str
    original_hash: str
    pseudonym: str
    start: int
    end: int


@dataclass(frozen=True)
class PseudonymizationResult:
    pseudonymized_text: str
    applied: list[AppliedMapping]


class ConsistentPseudonymizer:
    def __init__(
        self,
        *,
        analyzer: AnalyzerEngine,
        mapping_store: MappingStore,
        salt: str,
        faker_locale: str = "es_ES",
        language: str = "es",
    ) -> None:
        self._analyzer = analyzer
        self._store = mapping_store
        self._salt = salt.encode("utf-8")
        self._language = language
        self._faker = Faker(faker_locale)
        # Cross-call consistency comes from the store, not from the RNG.
        self._faker.seed_instance(0)
        self._generators: dict[str, Callable[[], str]] = {
            "PERSON": self._faker.name,
            "EMAIL_ADDRESS": self._faker.ascii_company_email,
            "LOCATION": self._faker.city,
            "BUDGET_ID": lambda: (
                f"BUDGET-{self._faker.random_int(2020, 2029)}-{self._faker.random_int(0, 9999):04d}"
            ),
            "CLIENT_CODE": lambda: f"CLI-{self._faker.random_int(0, 9999):04d}",
        }

    def pseudonymize(
        self,
        text: str,
        *,
        entities: list[str] | None = None,
    ) -> PseudonymizationResult:
        results = self._analyzer.analyze(text=text, language=self._language, entities=entities)
        results = _drop_overlaps(results)
        if not results:
            return PseudonymizationResult(pseudonymized_text=text, applied=[])

        # End offset descending so later edits do not shift earlier ones.
        results.sort(key=lambda r: r.end, reverse=True)

        out = text
        applied: list[AppliedMapping] = []
        for r in results:
            original_hash = self._hash(text[r.start : r.end])
            factory = self._generators.get(r.entity_type, self._fallback_pseudonym)
            pseudonym = self._store.lookup_or_create(
                entity_type=r.entity_type,
                original_hash=original_hash,
                new_pseudonym_factory=factory,
            )
            out = out[: r.start] + pseudonym + out[r.end :]
            applied.append(
                AppliedMapping(
                    entity_type=r.entity_type,
                    original_hash=original_hash,
                    pseudonym=pseudonym,
                    start=r.start,
                    end=r.end,
                )
            )

        return PseudonymizationResult(pseudonymized_text=out, applied=applied)

    def _hash(self, value: str) -> str:
        return hmac.new(self._salt, value.encode("utf-8"), hashlib.sha256).hexdigest()

    def _fallback_pseudonym(self) -> str:
        return f"REDACTED-{self._faker.uuid4()[:8]}"


def _drop_overlaps(results: list) -> list:
    """Keep the widest of any overlapping detections (ties: higher score first)."""
    kept: list = []
    for r in sorted(results, key=lambda r: (r.end - r.start, r.score), reverse=True):
        if all(r.end <= k.start or r.start >= k.end for k in kept):
            kept.append(r)
    return kept
